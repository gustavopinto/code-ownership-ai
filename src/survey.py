def likert(v):
    m = re.match(r"\s*(\d)", v or "")
    return int(m.group(1)) if m else None


def num(v):
    v = (v or "").strip().replace("%", "").replace(",", ".")
    return float(v) if v else None


def score(d, i):
    v = d["L"][i]
    return None if v is None else (6 - v if i in REVERSE else v)


