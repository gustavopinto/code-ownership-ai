def is_anonymized(path):
    with open(path, encoding="utf-8") as f:
        return next(csv.reader(f))[-len(REPO_COLUMNS):] == REPO_COLUMNS


def load(args):
    if is_anonymized(args.responses):
        return load_anonymized(args.responses)
    rows = list(csv.reader(open(args.responses, encoding="utf-8")))[1:]
    ident = json.load(open(args.identities, encoding="utf-8"))
    fix = {k.lower(): v for k, v in ident.get("fix_repo", {}).items()}
    pats = {k.lower(): v for k, v in ident.get("author_patterns", {}).items()}
    gender = {r["resposta_original"].strip().lower(): r["codigo"]
              for r in csv.DictReader(open(args.gender_codebook, encoding="utf-8"))}
    data = []
    for x in rows:
        user = re.sub(r"^https?://github\.com/", "", x[1].strip()).strip("/").lstrip("@")
        repo = fix.get(user.lower(), x[2].split("/")[-1])
        d = dict(user=user, repo=repo, fixed=repo != x[2].split("/")[-1],
                 author_pattern=pats.get(user.lower(), re.escape(user.lower())),
                 age=x[3], gender=gender.get(x[4].strip().lower(), "Blank" if not x[4].strip() else "Other"),
                 semester=x[5], years=x[6], experience=[t.strip() for t in x[7].split(";") if t.strip()],
                 freq=x[16].lower(), tools=x[17].lower(), tasks=x[18].lower(), sdd=x[19].lower(),
                 L={i: likert(x[i]) for i in range(8, 50)},
                 ideas_me=num(x[51]), ideas_agent=num(x[52]), code_me=num(x[53]), code_agent=num(x[54]),
                 read=num(x[55]), hours=num(x[56]),
                 open={k: x[i].strip() for k, i in OPEN.items()})
        for c, items in CONSTRUCTS.items():
            v = [score(d, i) for i in items if d["L"][i] is not None]
            d[c] = float(np.mean(v)) if v else None
        data.append(d)
    return data


def load_anonymized(path):
    """Respondents of data/survey-anonymized.csv: user is a random ID, repo the project's
    name in the paper, age and gender are blank, and the repository variables are read
    from the appended columns instead of the clones."""
    rows = list(csv.reader(open(path, encoding="utf-8")))[1:]
    data = []
    for x in rows:
        q, extra = x[:-len(REPO_COLUMNS)], dict(zip(REPO_COLUMNS, x[-len(REPO_COLUMNS):]))
        d = dict(user=q[1], repo=q[2], fixed=extra.pop("fixed") == "1", author_pattern=None,
                 age=q[3] or "Not released", gender=q[4] or "Not released",
                 semester=q[5], years=q[6], experience=[t.strip() for t in q[7].split(";") if t.strip()],
                 freq=q[16].lower(), tools=q[17].lower(), tasks=q[18].lower(), sdd=q[19].lower(),
                 L={i: likert(q[i]) for i in range(8, 50)},
                 ideas_me=num(q[51]), ideas_agent=num(q[52]), code_me=num(q[53]), code_agent=num(q[54]),
                 read=num(q[55]), hours=num(q[56]),
                 open={k: q[i].strip() for k, i in OPEN.items()})
        for k, v in extra.items():
            d[k] = num(v)
        d["own_commits"] = int(d["own_commits"])
        for c, items in CONSTRUCTS.items():
            v = [score(d, i) for i in items if d["L"][i] is not None]
            d[c] = float(np.mean(v)) if v else None
        data.append(d)
    return data


def add_repository_variables(data, projects_dir):
    by_folder = {}
    for pid, name, folder, path in repos(projects_dir):
        commits = load_commits(path)
        rows, (traced, total) = spec_analysis.analyze(path)
        log = [l.lower() for l in git(path, "log", "--format=%an|%ae").splitlines() if l]
        by_folder[folder] = dict(
            agent_commits=sum(authorship(c) == "agent" for c in commits) / len(commits),
            specs_by_agent=(sum(r["author"] == "agent" for r in rows) / len(rows)) if rows else None,
            sessions=len(sessions(path)),
            traced=traced / total if total else None,
            log=log, commits=commits)
    for d in data:
        r = by_folder[d["repo"]]
        d["repo_agent_commits"] = r["agent_commits"]
        d["repo_specs_by_agent"] = r["specs_by_agent"]
        d["repo_sessions"] = r["sessions"]
        d["repo_traced"] = r["traced"]
        mine = sum(1 for l in r["log"] if re.search(d["author_pattern"], l))
        d["own_commits"] = mine
        d["own_commit_share"] = mine / len(r["log"]) if r["log"] else None
        # Calibration: how the student's own commits declare their origin
        own = [c for c in r["commits"]
               if re.search(d["author_pattern"], f"{c['author']}|{c['email']}".lower())]
        kinds = [commit_origin(c) for c in own]
        declared = [k for k in kinds if k != "undeclared"]
        d["own_declared"] = len(declared)
        d["own_hand_share"] = (sum(k in ("handwritten", "agent + manual") for k in declared) / len(declared)
                               if declared else None)
        d["own_handwritten_share"] = (sum(k == "handwritten" for k in declared) / len(declared)
                                      if declared else None)


def commit_origin(c):
    """handwritten (Agent: none), agent + manual, agent, or undeclared."""
    values = [v.lower() for v in re.findall(r"^\s*Agent\s*:\s*(.+?)\s*$", c["body"], re.I | re.M)]
    if any(re.match(r"^(none|nenhum|nenhuma)\b", v) for v in values):
        return "handwritten"
    if any("manual" in v for v in values):
        return "agent + manual"
    if values or authorship(c) == "agent":
        return "agent"
    return "undeclared"


def calibration(data):
    """Self-attributed share of the code against the origin declared in one's own commits."""
    print("\nRQ4 calibration (self-report vs. own commits)")
    xs = [d for d in data if d["own_hand_share"] is not None and d["code_me"] is not None]
    print(f"respondents with declared own commits: {len(xs)} of {len(data)}; "
          f"without own commits: {sum(1 for d in data if d['own_commits'] == 0)}")
    for key, label in (("own_hand_share", "handwritten or agent + manual"),
                       ("own_handwritten_share", "handwritten only")):
        rho, p = stats.spearmanr([d["code_me"] for d in xs], [d[key] for d in xs])
        v = [100 * d[key] for d in xs]
        print(f"  share of own declared commits {label}: median {np.median(v):.0f}% "
              f"(Q1 {np.percentile(v, 25):.0f}, Q3 {np.percentile(v, 75):.0f}); "
              f"Spearman with % code attributed to self: rho={rho:+.2f}, p={p:.3f}")
    zero = [d for d in xs if d["own_hand_share"] == 0]
    print(f"  no own commit with a hand in the code: {len(zero)}; their self-attributed code: median "
          f"{np.median([d['code_me'] for d in zero]) if zero else 0:.0f}%, "
          f"{sum(d['code_me'] >= 20 for d in zero)} attribute at least 20%")
    over = [d for d in xs if d["code_me"] > 100 * d["own_hand_share"] + 20]
    under = [d for d in xs if d["code_me"] < 100 * d["own_hand_share"] - 20]
    print(f"  self-report more than 20 points above the record: {len(over)}; below: {len(under)}")


